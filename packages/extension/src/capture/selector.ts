/**
 * Stable CSS selectors for pinned elements. Prefers identifiers a developer wrote
 * (ids, test ids, names, labels) over generated ones, and falls back to a short
 * path of tags and stable class names, adding :nth-of-type only where needed.
 */

const TEST_ATTRIBUTES = ["data-testid", "data-test", "data-cy", "data-qa"] as const;
const LABEL_ATTRIBUTES = ["name", "aria-label"] as const;
const MAX_CLASSES_PER_STEP = 2;
const MAX_CLASS_LENGTH = 40;
const MAX_ATTRIBUTE_VALUE_LENGTH = 80;

/** A selector that matches exactly `element` within its document. */
export function buildSelector(element: Element): string {
  const root = element.ownerDocument;
  const anchored = uniqueAnchor(element, root);
  if (anchored !== undefined) return anchored;

  const steps: string[] = [];
  let current: Element | null = element;
  while (current !== null && current !== root.documentElement) {
    const parent: Element | null = current.parentElement;
    const anchor = parent === null ? undefined : uniqueAnchor(parent, root);
    steps.unshift(stepFor(current));
    const candidate = [anchor, ...steps].filter((step) => step !== undefined).join(" > ");
    // A position alone breaks as soon as the page changes, so keep it anchored.
    const stable = anchor !== undefined || !candidate.includes(":nth-of-type");
    if (stable && isUnique(candidate, element, root)) return candidate;
    if (anchor !== undefined) break;
    current = parent;
  }
  return pathWithPositions(element);
}

/** An id, test id, name or label selector that matches only this element. */
function uniqueAnchor(element: Element, root: Document): string | undefined {
  const { id } = element;
  if (id !== "" && isStableIdentifier(id)) {
    const selector = `#${cssEscape(id)}`;
    if (isUnique(selector, element, root)) return selector;
  }
  const tag = element.localName;
  for (const name of [...TEST_ATTRIBUTES, ...LABEL_ATTRIBUTES]) {
    const value = element.getAttribute(name);
    if (value === null || value === "" || value.length > MAX_ATTRIBUTE_VALUE_LENGTH) continue;
    const selector = `${tag}[${name}="${cssEscapeString(value)}"]`;
    if (isUnique(selector, element, root)) return selector;
  }
  return undefined;
}

function stepFor(element: Element): string {
  const classes = stableClasses(element).slice(0, MAX_CLASSES_PER_STEP);
  const base = element.localName + classes.map((name) => `.${cssEscape(name)}`).join("");
  const parent = element.parentElement;
  if (parent === null) return base;
  const twins = Array.from(parent.children).filter((child) => child.matches(base));
  return twins.length > 1 ? `${element.localName}${nthOfType(element)}` : base;
}

/** Last resort: a full path from the root with a position at every step. */
function pathWithPositions(element: Element): string {
  const steps: string[] = [];
  let current: Element | null = element;
  while (current !== null && current !== element.ownerDocument.documentElement) {
    steps.unshift(`${current.localName}${nthOfType(current)}`);
    current = current.parentElement;
  }
  return ["html", ...steps].join(" > ");
}

function nthOfType(element: Element): string {
  let index = 1;
  for (
    let sibling = element.previousElementSibling;
    sibling;
    sibling = sibling.previousElementSibling
  ) {
    if (sibling.localName === element.localName) index += 1;
  }
  return `:nth-of-type(${index})`;
}

function isUnique(selector: string, element: Element, root: Document): boolean {
  try {
    const matches = root.querySelectorAll(selector);
    return matches.length === 1 && matches[0] === element;
  } catch {
    return false;
  }
}

/** Class names a person wrote, not ones generated by CSS-in-JS or CSS modules. */
export function stableClasses(element: Element): string[] {
  return Array.from(element.classList).filter(isStableClass);
}

function isStableClass(name: string): boolean {
  if (name.length > MAX_CLASS_LENGTH || !/^[A-Za-z][\w-]*$/.test(name)) return false;
  if (/^(css|sc|jsx|emotion|styled|svelte|astro)-/i.test(name)) return false;
  if (/__[A-Za-z0-9_-]{5,}$/.test(name)) return false;
  return isStableIdentifier(name);
}

/** Rejects identifiers that look generated: long digit runs or framework prefixes. */
function isStableIdentifier(value: string): boolean {
  if (/\d{4,}/.test(value) || /^\d/.test(value)) return false;
  if (/^(ember|react-|radix-|headlessui-|mui-|:r)/i.test(value) || value.includes(":")) {
    return false;
  }
  return true;
}

/** CSS.escape for identifiers, which some DOM implementations lack. */
export function cssEscape(value: string): string {
  return Array.from(value)
    .map((char, index) => {
      const code = char.codePointAt(0) ?? 0;
      if (code === 0) return "\uFFFD";
      if ((code >= 0x1 && code <= 0x1f) || code === 0x7f) return `\\${code.toString(16)} `;
      if (index === 0 && /\d/.test(char)) return `\\${code.toString(16)} `;
      if (index === 0 && char === "-" && value.length === 1) return "\\-";
      if (code >= 0x80 || /[\w-]/.test(char)) return char;
      return `\\${char}`;
    })
    .join("");
}

/** Escape a value for a double-quoted attribute selector. */
function cssEscapeString(value: string): string {
  return value.replace(/["\\]/g, "\\$&").replace(/\n/g, "\\a ");
}
